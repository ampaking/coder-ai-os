  [ -f "$OUT" ] || { echo "snapshot missing — run .coder-ai-os-script/update-ai-context.sh"; exit 1; }
  STORED="$(sed -n 's/^> Fingerprint: \([0-9]* [0-9]*\).*/\1/p' "$OUT" | head -1)"
  [ -n "$STORED" ] || { echo "snapshot has no fingerprint (user-owned or pre-fingerprint) — cannot check"; exit 0; }
