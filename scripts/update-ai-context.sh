# The report body is best-effort formatting: `head -N` truncation legitimately makes
# upstream commands exit via SIGPIPE (141), and empty grep matches return 1. Relax
# errexit/pipefail here so a truncated or empty section never aborts the whole write.
set +e +o pipefail

{
  echo "# Project Snapshot"
  echo
  echo "> Generated by \`.coder-ai-os-script/update-ai-context.sh\` — do not hand-edit."
  echo "> Deterministic structural facts only. Regenerate when the repo's shape changes."
  echo "> Use rg for cheap location; use the code index (CodeGraph MCP) for caller/impact queries;"
  echo "> this file is the orientation fallback. Read it only when repo-wide orientation is needed."
  echo "> Fingerprint: $FINGERPRINT (path-list checksum). Verify freshness BEFORE trusting this map:"
  echo "> \`.coder-ai-os-script/update-ai-context.sh --check\` — if STALE, regenerate first."
  echo "> Memory scope: $(memory_scope)"
  echo

  echo "## Languages (by tracked file extension)"
  echo '```'
  printf '%s\n' "$FILES" \
    | sed -n 's|.*/||; s|^.*\.\([A-Za-z0-9_]*\)$|\1|p' \
    | grep -vE '^[0-9]+$' \
    | sort | uniq -c | sort -nr | head -15
  echo '```'
  echo

  echo "## Top-level structure (depth 2)"
  echo '```'
  find . -maxdepth 2 \
    -not -path './.git' -not -path './.git/*' \
    -not -path './node_modules' -not -path './node_modules/*' \
    -not -path '*/.env*' \
    -not -path './.codegraph' -not -path './.codegraph/*' \
    2>/dev/null | sed 's|^\./||' | sort | head -200
  echo '```'
  echo

  echo "## Build / manifest files"
  echo '```'
  printf '%s\n' "$FILES" \
    | grep -E '(^|/)(package\.json|pnpm-workspace\.yaml|tsconfig\.json|pyproject\.toml|setup\.py|requirements\.txt|Cargo\.toml|go\.mod|pom\.xml|build\.gradle|Gemfile|composer\.json|Makefile|CMakeLists\.txt|Dockerfile|docker-compose\.ya?ml)$' \
    | sort || echo "(none found)"
  echo '```'
  echo

  echo "## Workspace packages / indexable units (heuristic monorepo map)"
  echo "Package -> manifest -> name -> internal deps -> its atlas map (L1). Work owner-first,"
  echo "one package in flight (monorepo-change skill); pick the owning unit here without scanning."
  echo "Atlas (folder/file graphs + symbol tables): .ai/symbols/INDEX.md; per unit on demand:"
  echo '  .coder-ai-os-script/update-ai-context.sh --symbols <dir>          (writes .ai/symbols/<dir>.md maps)'
  echo '  .coder-ai-os-script/update-ai-context.sh --symbols <dir> --check  (fresh? STALE = regenerate first)'
  echo '  .coder-ai-os-script/update-ai-context.sh --graph <dir>            (enrich maps: used-by + classified'
  echo '                                                         unreferenced-symbol verification)'
  echo '  .coder-ai-os-script/update-ai-context.sh --refresh                (after a task: regenerate exactly'
  echo '                                                         the maps your changes touched)'
  echo "Usages of a symbol across the app: find which units depend on its owner (deps below +"
  echo "module flow), then rg -w <name> ONLY inside those dirs — never a repo-wide scan."
  echo "What did I change? .coder-ai-os-script/update-ai-context.sh --changed <dir> — added/removed/moved"
  echo "functions vs git HEAD, per file (body-only edits: git diff)."
  echo '```'
  # E1 — source root: nested projects (src/sat/backend/...) hide their modules behind
  # wrapper dirs. The longest common directory prefix of all source files is the honest
  # graph root; units and flow are computed one segment BELOW it. Empty prefix = repo root
  # (multiple clusters at top level) = previous behavior.
  SRCROOT="$(printf '%s\n' "$FILES" | grep -E "$SRC_EXT_RE" | awk -F/ '
    NR == 1 { n = NF - 1; for (i = 1; i <= n; i++) p[i] = $i; next }
    { m = NF - 1; if (m < n) n = m
      for (i = 1; i <= n; i++) if (p[i] != $i) { n = i - 1; break } }
    END { s = ""; for (i = 1; i <= n; i++) s = s (i > 1 ? "/" : "") p[i]; print s }')"
  STRIP="${SRCROOT:+$SRCROOT/}"
  [ -n "$SRCROOT" ] && echo "source root: $SRCROOT (longest common source prefix; units live below it)"
  TOPS="$(printf '%s\n' "$FILES" | grep -E "$SRC_EXT_RE" \
    | awk -v r="$STRIP" '{ if (r != "") { if (index($0, r) != 1) next; $0 = substr($0, length(r) + 1) } print }' \
    | grep '/' | cut -d/ -f1 | sort -u \
    | grep -vE '^(node_modules|vendor|dist|build|target|docs?)$' | grep -v '^\.' | head -30)"
  PKG_MANIFESTS="$(printf '%s\n' "$FILES" \
    | grep -E '(^|/)(package\.json|pyproject\.toml|setup\.py|Cargo\.toml|go\.mod|pom\.xml|build\.gradle|composer\.json)$' \
    | grep '/' \
    | grep -vE '(^|/)(node_modules|vendor|dist|build|target|\.venv|venv)/' | head -60)"
  if [ -z "$PKG_MANIFESTS" ]; then
    echo "(no nested manifests — single-package repo)"
  else
    MAP_TMP="$(mktemp)"; NAMES_TMP="$(mktemp)"
    true > "$MAP_TMP"
    while IFS= read -r m; do
      [ -f "$m" ] || continue
      d="${m%/*}"
      case "$m" in
        */package.json)   n="$(sed -n 's/.*"name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$m" | head -1)" ;;
        */Cargo.toml)     n="$(sed -n 's/^name[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' "$m" | head -1)" ;;
        */pyproject.toml) n="$(sed -n 's/^name[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' "$m" | head -1)" ;;
        */go.mod)         n="$(sed -n 's/^module[[:space:]]*//p' "$m" | head -1)" ;;
        *)                n="" ;;
      esac
      printf '%s\t%s\t%s\n' "$d" "${m##*/}" "${n:-?}" >> "$MAP_TMP"
    done <<PKGEOF
$PKG_MANIFESTS
PKGEOF
    cut -f3 "$MAP_TMP" | grep -v '^?$' | sort -u > "$NAMES_TMP"
    # Phantom-unit filter: a nested manifest whose name can't be resolved (a stray
    # setup.py deep inside another package's source) is NOT a real unit — its files
    # belong to the enclosing package's maps.
    awk -F '\t' '
      NR == FNR { dirs[$1] = 1; next }
      {
        if ($3 == "?") { for (d in dirs) if (d != $1 && index($1, d "/") == 1) next }
        print
      }
    ' "$MAP_TMP" "$MAP_TMP" > "$MAP_TMP.f" && mv "$MAP_TMP.f" "$MAP_TMP"
    while IFS="$(printf '\t')" read -r d mf n; do
      deps=""
      if [ -s "$NAMES_TMP" ] && [ -f "$d/$mf" ]; then
        deps="$({ grep -oE '"[^"[:space:]]+"' "$d/$mf" | tr -d '"'; \
                  sed -n 's/^\([A-Za-z0-9_.@/-]\{1,\}\)[[:space:]]*=.*/\1/p' "$d/$mf"; } \
                | sort -u | grep -Fxf "$NAMES_TMP" 2>/dev/null \
                | grep -Fxv "$n" | head -8 | paste -sd, -)"
      fi
      if [ -n "$deps" ]; then printf '%s  [%s]  %s  deps-> %s  map: %s\n' "$d" "$mf" "$n" "$deps" "$(map_out "$d")"
      else printf '%s  [%s]  %s  map: %s\n' "$d" "$mf" "$n" "$(map_out "$d")"; fi
    done < "$MAP_TMP"
    rm -f "$MAP_TMP" "$NAMES_TMP"
  fi
  # Bare units: source dirs one segment below the source root, no manifest required
  # (works in repos with no pyproject/package.json at all) — plus the source root and
  # repo root, so nested, single-package, and flat repos all get the same L0->L1->L2 chain.
  # Paths printed are full repo-relative so the --symbols command is copy-pasteable.
  while IFS= read -r t; do
    [ -n "$t" ] || continue
    printf '%s\n' "$PKG_MANIFESTS" | grep -q "^$STRIP$t/" && continue
    printf '%s\n' "$FILES" | grep -E "^$STRIP$t/" | grep -qE "$SRC_EXT_RE" || continue
    printf '%s  (no manifest)  map: %s\n' "$STRIP$t" "$(map_out "$STRIP$t")"
  done <<TOPSEOF
$TOPS
TOPSEOF
  [ -n "$SRCROOT" ] && echo "$SRCROOT  (source root)  map: $(map_out "$SRCROOT")"
  echo ".  (repo root)  map: $(map_out .)"
  echo '```'
  echo

  echo "## Module flow (heuristic top-level import graph)"
  echo "Directed edges between top-level dirs, aggregated from import/use/require lines and"
  echo "layered top-to-bottom: [entry] imports others; [base] is imported (api -> ... -> db)."
  echo "File-level only. For function/class callers/impact use the code index (CodeGraph MCP)."
  echo '```'
  if [ "$(printf '%s\n' "$TOPS" | grep -c .)" -lt 2 ]; then
    echo "(fewer than two top-level source dirs — no graph)"
  else
    TOPS_CSV="$(printf '%s\n' "$TOPS" | paste -sd, -)"
    EDGE_LINES="$(grep -rnE \
      --include='*.py' --include='*.ts' --include='*.tsx' --include='*.js' --include='*.jsx' \
      --include='*.go' --include='*.rs' --include='*.rb' --include='*.java' --include='*.php' \
      --include='*.cs' --include='*.sh' \
      --exclude-dir=node_modules --exclude-dir=vendor --exclude-dir=dist --exclude-dir=build \
      --exclude-dir=target --exclude-dir=.git --exclude-dir=.venv --exclude-dir=venv --exclude-dir=.ai \
      '^[[:space:]]*(import|from|use|require|include|source)[[:space:](]' . 2>/dev/null \
      | awk -v tops="$TOPS_CSV" -v sroot="$STRIP" '
          BEGIN {
            n = split(tops, T, ",")
            for (i = 1; i <= n; i++) { Tesc[i] = T[i]; gsub(/[][().*+?^$\\|{}]/, "\\\\&", Tesc[i]) }
          }
          {
            p1 = index($0, ":"); if (p1 == 0) next
            src = substr($0, 1, p1 - 1); sub(/^\.\//, "", src)
            if (sroot != "") { if (index(src, sroot) != 1) next; src = substr(src, length(sroot) + 1) }
            k = index(src, "/"); if (k == 0) next
            s = substr(src, 1, k - 1)
            rest = substr($0, p1 + 1); p2 = index(rest, ":"); if (p2 == 0) next
            line = substr(rest, p2 + 1)
            for (i = 1; i <= n; i++) {
              if (T[i] == s) continue
              if (line ~ ("(^|[^A-Za-z0-9_])" Tesc[i] "($|[^A-Za-z0-9_-])")) e[s "->" T[i]]++
            }
          }
          END { for (x in e) print e[x], x }' \
      | sort -rn | head -15)"
    if [ -z "$EDGE_LINES" ]; then
      echo "(no cross-directory imports detected)"
    else
      printf '%s\n' "$EDGE_LINES" | awk '
        { split($2, p, "->"); out[p[1]] += $1; inn[p[2]] += $1; seen[p[1]]; seen[p[2]] }
        END {
          e = ""; m = ""; b = ""
          for (d in seen) {
            if (out[d] && !inn[d]) e = e d " "
            else if (inn[d] && !out[d]) b = b d " "
            else m = m d " "
          }
          if (e != "") print "[entry] " e
          if (m != "") print "[mid]   " m
          if (b != "") print "[base]  " b
        }'
      echo "--- flow tree (imports point down; cycles marked) ---"
      printf '%s\n' "$EDGE_LINES" | LC_ALL=C sort -k2,2 | awk '
        function ptree(d, pref,   n, arr, i, c, j, m, conn, cpref) {
          onpath[d] = 1; printed[d] = 1
          n = split(ch[d], arr, ","); m = 0
          for (i = 1; i <= n; i++) if (arr[i] != "") m++
          j = 0
          for (i = 1; i <= n; i++) {
            c = arr[i]; if (c == "") continue; j++
            conn = (j == m) ? "`-> " : "|-> "
            cpref = (j == m) ? "    " : "|   "
            if (c in onpath)        print pref conn c "  <- cycle"
            else if (c in printed)  print pref conn c "  (shown above)"
            else { print pref conn c; ptree(c, pref cpref) }
          }
          delete onpath[d]
        }
        { split($2, p, "->")
          if (!(p[1] in idx)) { order[++N] = p[1]; idx[p[1]] }
          if (!(p[2] in idx)) { order[++N] = p[2]; idx[p[2]] }
          ch[p[1]] = ch[p[1]] p[2] ","
          inn[p[2]]++; out[p[1]]++ }
        END {
          for (i = 1; i <= N; i++) { d = order[i]
            if (out[d] && !inn[d] && !(d in printed)) { print d; ptree(d, "") } }
          for (i = 1; i <= N; i++) { d = order[i]
            if (out[d] && !(d in printed)) { print d "  (in a cycle)"; ptree(d, "") } }
        }'
      echo "--- edges (count src->dst) ---"
      printf '%s\n' "$EDGE_LINES"
    fi
  fi
  echo '```'
  echo

  echo "## Entry points (heuristic)"
  echo '```'
  printf '%s\n' "$FILES" \
    | grep -E '(^|/)(main|index|app|server|cli|__main__)\.[A-Za-z]+$|(^|/)cmd/[^/]+/main\.go$' \
    | sort | head -40 || echo "(none found)"
  echo '```'
  echo

  echo "## Test directories"
  echo '```'
  printf '%s\n' "$FILES" \
    | grep -E '(^|/)(tests?|__tests__|spec|e2e)/' \
    | sed 's|/[^/]*$||' | sort -u | head -50 || echo "(none found)"
  echo '```'
} > "$OUT"

