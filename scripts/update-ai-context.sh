      /^#/ { next }
      { k = $1 FS $2 FS $3
        if (!(k in old)) print "+ " $2 " " $3 " " $1 ":" $4
        else { if (old[k] != $4) print "~ " $2 " " $3 " " $1 ":" old[k] "->" $4; delete old[k] } }
      END { for (k in old) { split(k, a, FS); print "- " a[2] " " a[3] " " a[1] ":" old[k] } }
    ' "$BOUT" "$W/new.tsv" | LC_ALL=C sort)"
    if [ -z "$CHANGES" ]; then echo "no structural changes vs baseline"; exit 0; fi
    echo "structural changes vs baseline (+added -removed ~moved) — verify each against the"
    echo "task's declared Files; changes OUTSIDE declared scope are unrelated edits to flag:"
    printf '%s\n' "$CHANGES"; exit 1
