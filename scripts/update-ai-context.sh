# --check: is the existing snapshot still fresh? Structural only — the fingerprint is a
# checksum of the tracked-path LIST (never contents), so it changes exactly when files are
# added/removed/renamed. Exit 0 fresh, 1 stale/missing. Agents run this before trusting the map.
